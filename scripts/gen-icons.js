#!/usr/bin/env node
// Generates src/core/icons.generated.ts from @primer/octicons, keeping only the
// icons listed below so the bundles stay small. Run: `npm run gen:icons`.

const fs = require('fs');
const path = require('path');
const data = require('@primer/octicons/build/data.json');

const ICONS = [
  'alert', 'alert-fill', 'arrow-down', 'arrow-up', 'arrow-right', 'bell', 'bell-fill', 'check', 'check-circle',
  'check-circle-fill', 'chevron-down', 'chevron-right', 'chevron-up', 'clock', 'code-review', 'comment',
  'comment-discussion', 'copy', 'database', 'diff', 'dot-fill', 'eye', 'file', 'file-diff', 'filter', 'fold', 'gear',
  'git-branch', 'git-commit', 'git-merge', 'git-pull-request', 'git-pull-request-draft', 'globe', 'heart', 'inbox',
  'info', 'issue-opened', 'key', 'link', 'link-external', 'log', 'mark-github', 'moon', 'pencil', 'person',
  'question', 'rocket', 'search', 'shield-check', 'sign-out', 'skip', 'sliders', 'sparkle-fill', 'stop', 'sun',
  'sync', 'tag', 'trash', 'unfold', 'x', 'x-circle', 'x-circle-fill', 'zap', 'command-palette', 'paintbrush',
  'stopwatch', 'versions', 'repo', 'people', 'hourglass', 'checklist', 'tools', 'eye-closed', 'history', 'plug',
  'bug', 'book', 'law', 'home', 'terminal', 'download', 'upload',
];

const missing = ICONS.filter((n) => !data[n]?.heights?.['16']);
if (missing.length) {
  console.error('Unknown octicons:', missing.join(', '));
  process.exit(1);
}

const entries = ICONS.map((name) => `  '${name}': ${JSON.stringify(data[name].heights['16'].path)},`).join('\n');

const out = `// AUTO-GENERATED by scripts/gen-icons.js from @primer/octicons — do not edit by hand.
// Add a name to ICONS in the script and run \`npm run gen:icons\`.

export const ICON_PATHS = {
${entries}
} as const;

export type IconName = keyof typeof ICON_PATHS;
`;

const dest = path.join(__dirname, '..', 'src', 'core', 'icons.generated.ts');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`Wrote ${ICONS.length} icons to ${path.relative(process.cwd(), dest)}`);
